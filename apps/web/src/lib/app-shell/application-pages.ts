export type ApplicationPage = (typeof applicationPages)[number]
export type ApplicationPagePath = ApplicationPage["url"]

export function visibleApplicationPages(
  canAdminister: boolean,
  canManage: boolean
) {
  return applicationPages.filter((page) => {
    if (page.visibility === "admin") return canAdminister
    if (page.visibility === "manager") return canManage
    return true
  })
}
